// Extracts only the game-icons.net icons referenced by src/ui/icons/iconMap.ts into
// src/ui/icons/iconData.ts, so the game bundles a few KB instead of the whole icon set.
// Run with `npm run build:icons` after editing iconMap.ts. Needs the dev dependency
// @iconify-json/game-icons. Icons are CC BY 3.0 (see ASSETS.md).
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const set = require('@iconify-json/game-icons/icons.json');

const mapPath = path.resolve('src', 'ui', 'icons', 'iconMap.ts');
const mapSource = fs.readFileSync(mapPath, 'utf8');

// Every quoted lowercase-hyphen id used as a value: `key: 'icon-id'`
const ids = [...new Set([...mapSource.matchAll(/:\s*'([a-z0-9]+(?:-[a-z0-9]+)*)'/g)].map((m) => m[1]))].sort();

const missing = ids.filter((id) => !set.icons[id]);
if (missing.length > 0) {
  console.error(`[build-icons] Unknown game-icons ids: ${missing.join(', ')}`);
  process.exit(1);
}

const lines = ids.map((id) => `  '${id}': ${JSON.stringify(set.icons[id].body)}`);
const out = `// GENERATED by scripts/build-icons.mjs from game-icons.net (CC BY 3.0). Do not edit.
// Authors: Lorc, Delapouite and contributors. https://game-icons.net
export const ICON_VIEWBOX = '0 0 ${set.width ?? 512} ${set.height ?? 512}';

export const ICON_BODIES: Record<string, string> = {
${lines.join(',\n')}
};
`;

fs.writeFileSync(path.resolve('src', 'ui', 'icons', 'iconData.ts'), out);
console.log(`[build-icons] Wrote ${ids.length} icons.`);
